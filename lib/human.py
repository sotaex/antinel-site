def explain(term):
    """术语的首次出现解释。没有登记的术语直接报错，逼着补表。"""
    if term not in TERMS:
        raise KeyError("术语表里没有「%s」——先补 lib/human.py 的 TERMS" % term)
    return TERMS[term]
